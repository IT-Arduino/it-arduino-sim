/**
 * Показ данных, приходящих от API сайта.
 *
 * Отдельный модуль, а не функция внутри диалога, по одной причине: здесь
 * лежит поправка на особенность сервера, которую нужно уметь проверить
 * тестом, не поднимая React.
 */

/**
 * Дата изменения схемы — человеку.
 *
 * Сервер пишет `datetime.utcnow()` и отдаёт строку БЕЗ указания зоны:
 * «2026-08-28T12:00:00». По стандарту ECMAScript такая строка — дата-время без
 * смещения — читается как МЕСТНОЕ время, и в Москве дата съезжает на три часа
 * назад. Дописываем `Z`, если зоны нет.
 *
 * Ошибка эта тихая: значение остаётся правдоподобным, просто неверным, и
 * заметить её на глаз можно лишь у схемы, сохранённой около полуночи.
 *
 * Строку с зоной не трогаем — вдруг сервер однажды начнёт её присылать.
 * Неразбираемую возвращаем как есть: показать сырое значение честнее, чем
 * «Invalid Date».
 */
export function formatUpdatedAt(iso: string): string {
  const hasZone = /(?:Z|[+-]\d{2}:?\d{2})$/.test(iso);
  const d = new Date(hasZone ? iso : `${iso}Z`);
  if (Number.isNaN(d.getTime())) return iso;
  return d.toLocaleString('ru-RU', {
    day: 'numeric',
    month: 'long',
    hour: '2-digit',
    minute: '2-digit',
  });
}
