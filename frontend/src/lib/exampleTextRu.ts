/**
 * Swap the two user-facing strings, leaving everything else — id, code,
 * components, wires, tags — byte-identical. Returns the SAME object when
 * nothing is translated so the common path allocates nothing.
 */
export function translateExample(ex: ExampleProject): ExampleProject {
  const title = TITLE_RU[ex.id];
  const description = DESCRIPTION_RU[ex.id];
  if (!title && !description) return ex;
  return {
    ...ex,
    ...(title ? { title } : {}),
    ...(description ? { description } : {}),
  };
}

export function translateExamples(list: ExampleProject[]): ExampleProject[] {
  return list.map(translateExample);
}
