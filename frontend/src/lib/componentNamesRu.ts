/**
 * Русские названия и описания деталей каталога.
 *
 * Почему отдельный файл, а не i18next. Названия и описания деталей — не строки
 * интерфейса: они генерируются при сборке из метаданных `@wokwi/elements` в
 * `frontend/public/components-metadata.json` (см. `scripts/generate-component-metadata.ts`),
 * а `ComponentPickerModal` печатает `component.name` и `component.description`
 * как есть, без единого вызова `t()`. Класть полтораста записей в общий
 * словарь ради строк, которые до i18next не доходят, незачем — перевод
 * применяется там же, где форк уже фильтрует каталог.
 *
 * Правила перевода:
 *
 *   - маркировка прибора остаётся латиницей: 1N4007, BC547, 74HC00, LM358.
 *     Это международные обозначения, по ним ученик ищет деталь в магазине и в
 *     справочнике. Переводится только пояснение в скобках;
 *   - единицы по-русски: кОм, мкФ, нФ, пФ, мГн, мкГн, В, А, Вт;
 *   - десятичная запятая, как принято в русской технической записи;
 *   - логические элементы называются по ГОСТ: И, ИЛИ, НЕ, И-НЕ, ИЛИ-НЕ,
 *     исключающее ИЛИ. «AND Gate» — это «элемент И», а не «гейт AND».
 *
 * Детали, которых здесь нет, показываются с исходным названием. Это
 * намеренно: апстрим добавляет детали, и непереведённая новая деталь —
 * английская строка, а не пустая карточка.
 */

