/**
 * Подпись тэга по-русски. Незнакомый возвращается как есть — так новая
 * деталь апстрима покажет свои тэги по-английски, а не пустые чипы.
 */
export function tagLabelRu(tag: string): string {
  return TAG_RU[tag.toLowerCase()] ?? tag;
}

/** Название категории по-русски. Незнакомая возвращается как есть. */
export function categoryLabelRu(category: string): string {
  return CATEGORY_RU[category] ?? category;
}

/** Описание платы по-русски; undefined — тогда берётся исходное. */
export function boardDescriptionRu(boardKind: string): string | undefined {
  return BOARD_DESCRIPTION_RU[boardKind];
}

/**
 * Подставить русские название и описание.
 *
 * Возвращает исходный объект без изменений, если перевода нет: лишняя копия
 * на каждую непереведённую деталь ничего не даёт, а ссылочное равенство
 * иногда экономит перерисовку.
 */
export function translateComponent<
  T extends { id: string; name: string; description?: string; category?: string },
>(component: T): T {
  const ru = COMPONENT_RU[component.id];
  const alias = component.category ? CATEGORY_ALIASES[component.category] : undefined;
  if (!ru && !alias) return component;

  return {
    ...component,
    ...(alias ? { category: alias } : {}),
    ...(ru
      ? {
          name: ru.name,
          // Описание переводим, только если оно у нас есть. Английское описание
          // апстрима полезнее пустого места: по нему хотя бы понятно, что за
          // деталь.
          description: ru.description ?? component.description,
        }
      : {}),
  };
}

/** То же для списка. */
export function translateComponents<
  T extends { id: string; name: string; description?: string; category?: string },
>(components: T[]): T[] {
  return components.map(translateComponent);
}
