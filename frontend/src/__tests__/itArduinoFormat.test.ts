/**
 * Тесты показа дат от API сайта (src/lib/itArduinoFormat).
 *
 * Проверяется одна поправка, и она стоит теста именно потому, что ломается
 * тихо: сервер пишет `datetime.utcnow()` и отдаёт строку без указания зоны,
 * а браузер такую строку по стандарту читает как местное время. Дата
 * остаётся правдоподобной и просто оказывается неверной на величину
 * часового пояса — на глаз это видно только у схемы, сохранённой около
 * полуночи.
 *
 * Сравниваются не тексты вывода, а моменты времени: формат `toLocaleString`
 * зависит от версии ICU в Node, и тест, привязанный к строке «28 августа»,
 * сломался бы при обновлении рантайма, ничего не сказав о самой поправке.
 */
import { describe, it, expect } from 'vitest';

import { formatUpdatedAt } from '../lib/itArduinoFormat';

describe('formatUpdatedAt', () => {
  it('читает строку без зоны как UTC, а не как местное время', () => {
    // Один и тот же момент, записанный двумя способами. Без поправки вторая
    // строка сдвинулась бы на величину часового пояса.
    expect(formatUpdatedAt('2026-08-28T12:00:00')).toBe(formatUpdatedAt('2026-08-28T12:00:00Z'));
  });

  it('не трогает строку, в которой зона уже указана', () => {
    // 15:00 в зоне +03:00 — тот же момент, что 12:00 UTC.
    expect(formatUpdatedAt('2026-08-28T15:00:00+03:00')).toBe(
      formatUpdatedAt('2026-08-28T12:00:00Z'),
    );
  });

  it('понимает зону, записанную без двоеточия', () => {
    expect(formatUpdatedAt('2026-08-28T15:00:00+0300')).toBe(
      formatUpdatedAt('2026-08-28T12:00:00Z'),
    );
  });

  it('показывает время в местной зоне пользователя', () => {
    const utcNoon = new Date('2026-08-28T12:00:00Z');
    const hour = utcNoon.getHours().toString().padStart(2, '0');
    const minute = utcNoon.getMinutes().toString().padStart(2, '0');

    expect(formatUpdatedAt('2026-08-28T12:00:00')).toContain(`${hour}:${minute}`);
  });

  it('возвращает неразбираемое значение как есть, а не «Invalid Date»', () => {
    expect(formatUpdatedAt('позавчера')).toBe('позавчера');
  });

  it('не падает на пустой строке', () => {
    expect(formatUpdatedAt('')).toBe('');
  });
});
